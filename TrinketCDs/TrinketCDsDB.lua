local spell_to_item = {}
DB.UNIT_SPELL_TO_ITEM = spell_to_item

local function add_pair(spell_ID, item_ID)
    local list = spell_to_item[spell_ID]
    if not list then
        list = {}
        spell_to_item[spell_ID] = list
    end
    for i = 1, #list do
        if list[i] == item_ID then return end
    end
    list[#list + 1] = item_ID
end

